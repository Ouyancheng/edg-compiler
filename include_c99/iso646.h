/*
iso646.h -- Include file of operator name macros from Normative Addendum 1
            of the ISO C standard.
*/
#ifndef _ISO646_H
#define _ISO646_H

#define	and	&&
#define	and_eq	&=
#define	bitand	&
#define	bitor	|
#define	compl	~
#define	not	!
#define	not_eq	!=
#define	or	||
#define	or_eq	|=
#define	xor	^
#define	xor_eq	^=

#endif /* _ISO646_H */
