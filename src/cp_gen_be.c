static a_boolean is_implicitly_cast_integral_constant(a_constant_ptr con)
/*
Return TRUE if the indicated constant is an integral constant cast to
some other type, and the conversion is one that can be done implicitly.
This is used for calls of C-mode functions with parameters that
possibly involve prototype scope types.  For example:

  void f(struct A { int i; } *);
  void g(enum E { AA });
  main() {
    f(0);
    g(5);
  }

These cases are problems because the cast cannot be written explicitly
since the type cannot be named at the call site; therefore we detect them
and put them out as implicit conversions.  Note that for the 0 --> pointer
case we're not checking to see if a prototype scope type is involved in
the conversion, so some cases not involving such types will be rendered
as implicit conversions even though the conversion could be written
explicitly, but that's a good thing for a null pointer constant.  Implicit
conversions on nonconstants are handled in eok_cast processing.
*/
{
  a_boolean is_implicit_cast = FALSE;

  /* The implicit_cast flag is not checked here on purpose.  It's not set
     for the enum case. */
  if (con->kind == (a_constant_repr_kind)ck_integer) {
    a_type_ptr con_type = skip_typerefs(con->type);
    if (con_type->kind == (a_type_kind)tk_pointer &&
        cmplit_integer_constant(con, 0L) == 0) {
      /* Zero converted to a pointer type. */
      is_implicit_cast = TRUE;
    } else if (con_type->kind == (a_type_kind)tk_integer &&
               con_type->variant.integer.enum_type &&
               con_type->declared_in_function_prototype) {
      /* Any integral value converted to a prototype scope enum type. */
      is_implicit_cast = TRUE;
    }  /* if */
  }  /* if */
  return is_implicit_cast;
}  /* is_implicitly_cast_integral_constant */


static a_boolean pm_cast_is_unambiguous(a_constant_ptr constant)
/*
constant points at a ck_ptr_to_member constant.  If the constant requires
a cast to a base or derived class, and the cast is unambiguous when done in
one step instead of class-by-class, return TRUE.
*/
{
  a_boolean unambiguous_cast = FALSE;

  if (constant->variant.ptr_to_member.casting_base_class != NULL) {
    /* See if there is another base class with the same name as the one
       we're starting from.  If not, the cast is unambiguous. */
    if (!constant->variant.ptr_to_member.casting_base_class->ambiguous) {
      unambiguous_cast = TRUE;
    }  /* if */
  }  /* if */
  return unambiguous_cast;
}  /* pm_cast_is_unambiguous */


static void gen_initializer_constant(a_constant_ptr constant,
                                     a_type_ptr     type)
/*
Generate an initializer constant, which differs from a normal constant in
that it can contain aggregates and dynamic initializations.  type is
the type of the entity being initialized; it can be NULL if the constant
is not an aggregate or dynamic initialization, and if the entity being
initialized is not a reference.
*/
{
  a_constant_ptr sub_con;
  a_type_ptr     sub_type;
  a_field_ptr    field;
  a_boolean      array_case;

  if (constant->kind == (a_constant_repr_kind)ck_aggregate) {
    /* Aggregate constant (e.g., "{1, 2, 3}"). */
    write_tok_ch('{');
    /* Figure out the kind of aggregate so we can track the type as we
       work through constants. */
    type = skip_typerefs(type);
    array_case = (type->kind == (a_type_kind)tk_array);
    if (array_case) {
      /* Array -- each constant will fill an element of the array. */
      sub_type = type->variant.array.element_type;
    } else {
      check_assertion_str(is_class_type_kind(type->kind),
                          "gen_initializer_constant: bad aggregate type");
      /* A class, struct, or union.  The constants will fill nonstatic data
         members of the class. */
      field = next_initializable_field(
                                  type->variant.class_struct_union.field_list);
    }  /* if */
    /* Loop through the list of initializer constants. */
    for (sub_con = constant->variant.aggregate.first_constant;
         sub_con != NULL;) {
      /* Determine the type of the entity initialized by the next constant. */
      if (!array_case) {
        check_assertion_str(field != NULL,
                            "gen_initializer_constant: ran out of fields");
        sub_type = field->type;
        field = next_initializable_field(field->next);
      }  /* if */
      gen_initializer_constant(sub_con, sub_type);
      sub_con = sub_con->next;
      /* Stop after the last constant. */
      if (sub_con == NULL) break;
      write_tok_str(", ");
    }  /* for */
    write_tok_ch('}');
  } else if (constant->kind == (a_constant_repr_kind)ck_dynamic_init) {
    /* Dynamic initialization for an element of an aggregate. */
    gen_dynamic_init(constant->variant.dynamic_init, type,
                     /*parenthesized_init=*/FALSE,
                     /*force_parens=*/FALSE);
  } else if (constant->kind == (a_constant_repr_kind)ck_ptr_to_member &&
             pm_cast_is_unambiguous(constant)) {
    /* A pointer-to-member constant cast to a derived class where there
       is only one copy of the base class (the usual case) -- we can avoid
       the class-by-class casts to the derived type.  This is actually
       necessary to get around a cfront bug -- cfront generates bad C code for
       casts like that in initializer constants. */
    form_pm_constant(constant, /*minimal_casts*/TRUE, /*need_parens=*/TRUE,
                     &octl);
  } else if (type != NULL && is_reference_type(type)) {
    /* Initializing a reference.  The constant must be displayed with one
       level of indirection removed. */
    form_reference_init_constant(constant, /*need_parens=*/TRUE, &octl);
  } else if (il_header.source_language == sl_C &&
             is_implicitly_cast_integral_constant(constant)) {
    /* An integral constant that can be implicitly converted to another
       type.  Put out with the conversion implicit.  This is important in
       the case where the type involves a prototype scope type that cannot
       be named here. */
    form_integer_constant(constant, /*suppress_cast=*/TRUE,
                          /*need_parens=*/TRUE, &octl);
  } else {
    /* Normal constant. */
    gen_constant(constant, /*need_parens=*/TRUE);
  }  /* if */
}  /* gen_initializer_constant */


static void gen_storage_class(a_storage_class storage_class)
/*
Print the storage class and a space.  If there is no printable storage class,
omit the space.
*/
{
  char *str;

  switch (storage_class) {
    case sc_extern:
      str = "extern";
      break;
    case sc_static:
      str = "static";
      break;
    case sc_auto:
      str = "auto";
      break;
    case sc_unspecified:
      /* Print nothing. */
      goto done;
    case sc_register:
      str = "register";
      break;
    case sc_typedef:
      str = "typedef";
      break;
    default:
      unexpected_condition_str("gen_storage_class: bad storage class");
  }  /* switch */
  write_tok_str(str);
  write_space();
done:;
}  /* gen_storage_class */


static char *tag_kind(a_type_kind kind)
/*
Return a string that describes the tag kind for the indicated type, i.e.,
"class" or "enum".
*/
{
  char *str;

  switch (kind) {
    case tk_enum:   str = "enum";   break;
    case tk_class:  str = "class";  break;
    case tk_struct: str = "struct"; break;
    case tk_union:  str = "union";  break;
    default:        unexpected_condition_str("tag_kind: bad type kind");
  }  /* switch */
  return str;
}  /* tag_kind */


static void gen_tag_reference(a_type_ptr type)
/*
Generate a reference to the indicated type, which is a class, struct, union,
or enum.
*/
{
  a_source_sequence_entry_ptr saved_curr_source_sequence_entry;
  a_source_sequence_entry_ptr saved_sublist_parent_source_sequence_entry;

  if (type->definition_delayed) {
    /* Put out the definition if it is needed and was delayed because a
       non-autonomous definition appeared. */
    type->definition_delayed = FALSE;
    /* Save the current position in the source sequence stream and change it
       to the source sequence entry for the type. */
    saved_curr_source_sequence_entry = curr_source_sequence_entry;
    saved_sublist_parent_source_sequence_entry =
                                          sublist_parent_source_sequence_entry;
    curr_source_sequence_entry = type->source_corresp.source_sequence_entry;
    sublist_parent_source_sequence_entry = NULL;  /* Arbitrary. */
    /* Put out the definition. */
    if (type->kind == (a_type_kind)tk_enum) {
      gen_enum_definition(type);
    } else {
      gen_class_definition(type);
    }  /* if */
    /* Restore the source sequence list position. */
    curr_source_sequence_entry = saved_curr_source_sequence_entry;
    sublist_parent_source_sequence_entry =
                                    saved_sublist_parent_source_sequence_entry;
  } else {
    /* Put out a reference to the tag by name.  Note that unnamed tags will
       have been given compiler-generated names so they can be referred to. */
    write_tok_str(tag_kind(type->kind));
    write_space();
    gen_decl_name(&type->source_corresp, iek_type);
    type->declaration_put_out = TRUE;
  }  /* if */
}  /* gen_tag_reference */


static void gen_type_reference(a_type_ptr type)
/*
Generate a reference to the indicated type, which is a tag or a typedef.
A reference is not the definition unless the type is unnamed.
*/
{
  if (type->kind == (a_type_kind)tk_typeref) {
    /* A typedef. */
    gen_type_name(type);
  } else {
    /* A class, struct, union, or enum. */
    /* In C++, don't use "class X" instead of "X" unless that is required,
       e.g., because there's something else called "X" in the same scope. */
    if (il_header.source_language == sl_Cplusplus &&
        /* You can't omit the "class" etc. on a first use that's a declaration,
           except for a template entity (the declaration will have been put
           out, but declaration_put_out is not set). */
        (type->declaration_put_out ||
         (is_class_type_kind(type->kind) &&
          type->variant.class_struct_union.extra_info->
                                                 template_arg_list != NULL)) &&
        !type->definition_delayed &&
        !type->elaborated_type_specifier_needed) {
      /* Use just the type name. */
      gen_type_name(type);
    } else {
      /* Use an elaborated type specifier, e.g., "class X". */
      gen_tag_reference(type);
    }  /* if */
  }  /* if */
}  /* gen_type_reference */


static void gen_name_reference(char             *entry,
                               an_il_entry_kind kind)
/*
Routine to be called by the il_to_str routines to output a name.
*/
{
  /* Types get handled specially; everything else goes through the normal
     gen_name. */
  if (kind == iek_type) {
    gen_type_reference((a_type_ptr)entry);
  } else {
    gen_name((a_source_correspondence *)entry, kind);
  }  /* if */
}  /* gen_name_reference */


static void bypass_prototype_scope_type_src_seq_entries(void)
/*
Advance past any source sequence entries for types declared or defined
in a function declarator.  Mark those types so that their definitions
will be put out when they are encountered when generating the parameter types.
*/
{
  a_type_ptr                   type;
  a_src_seq_secondary_decl_ptr sec_decl;
  a_boolean                    is_definition;

  while (curr_src_seq_entry_is_type_decl(&type, &sec_decl, &is_definition)) {
    /* In C mode, we know all the types will be in the prototype scope,
       so it's easy to find the end of the list.  In C++, there can be
       declarations that appear in the function declarator but get entered
       in the file scope.  To skip those, we just skip non-autonomous tag
       declarations.  Of course, some of the types we skip might be from
       whatever follows the function declaration, but they would just get
       skipped in this same way, so it's harmless to skip them now. */
    if (il_header.source_language == sl_Cplusplus) {
      if (is_autonomous_decl(type, sec_decl)) break;
    } else {
      if (!type->declared_in_function_prototype) break;
    }  /* if */
    /* A type in the function declarator.  Skip over it and mark it for later
       processing. */
    skip_type_and_delay_definition(type, is_definition);
  }  /* while */
}  /* bypass_prototype_scope_type_src_seq_entries */


static void bypass_prototyped_param_src_seq_entries(void)
/*
Advance past any source sequence entries that are associated with parameter
declarations and types declared or defined in the function declarator of
the current function definition.  Mark such types so that their definitions
will be put out when they are encountered when generating the parameter types.
*/
{
  a_type_ptr                   type;
  a_src_seq_secondary_decl_ptr sec_decl;
  a_boolean                    is_definition;

  for (;;) {
    if (ss_entry_kind(curr_source_sequence_entry) == iek_variable) {
      /* Bypass a parameter declaration. */
      adv_curr_source_sequence_entry();
    } else if (ss_entry_kind(curr_source_sequence_entry) == iek_statement) {
      /* Stop on the opening brace of the function. */
      break;
    } else {
      /* Anything else should be a type declared or defined in the parameter
         list (and in the prototype scope, in C). */
      if (curr_src_seq_entry_is_type_decl(&type, &sec_decl, &is_definition)) {
        check_assertion_str(il_header.source_language == sl_Cplusplus ||
                            type->declared_in_function_prototype,
                      "bypass_prototyped_param_...: not prototype scope type");
        /* Skip past the source sequence entries for the type and mark the
           definition as delayed. */
        skip_type_and_delay_definition(type, is_definition);
      } else {
        unexpected_condition_str("bypass_prototyped_param_...: not a type");
      }  /* if */
    }  /* if */
  }  /* for */
}  /* bypass_prototyped_param_src_seq_entries */


static void gen_function_declarator_with_scope(a_type_ptr  type,
                                               a_scope_ptr scope)
/*
Output a function declarator for the indicated routine type.
This is the top-level type of a function definition only if scope
is non-NULL, in which case that is the function scope.
*/
{
  a_routine_type_supplement_ptr rtsp = type->variant.routine.extra_info;
  a_param_type_ptr              param;
  a_variable_ptr                param_var;

  /* The code here is similar to code in form_function_declarator. */
  if (scope != NULL) param_var = scope->variant.routine.parameters;
  write_tok_ch('(');
  /* A routine is put out as unprototyped if its interface is unprototyped
     or if this is the definition and the definition is old-style (i.e.,
     there was a prototyped declaration and then an old-style definition). */
  if (!rtsp->prototyped ||
      (scope != NULL && rtsp->old_style_params_scanned)) {
    /* Old-style list. */
    if (scope != NULL) {
      /* This is the definition, so put out the parameter names. */
      if (param_var != NULL) {
        for (;;) {
          gen_decl_name(&param_var->source_corresp, iek_variable);
          /* Stop after the last parameter. */
          param_var = param_var->next;
          if (param_var == NULL) break;
          /* Put out a separator and keep looping. */
          write_tok_str(", ");
        }  /* for */
      }  /* if */
    }  /* if */
  } else {
    /* Prototyped list. */
    param = rtsp->param_type_list;
    if (param == NULL) {
      /* The first argument is NULL, so this is a "void" parameter list.
         Write it as void in C, as empty in C++. */
      if (il_header.source_language == sl_C) {
        write_tok_str("void");
      }  /* if */
    } else {
      /* List the parameter types (and, if this is the definition, names
         too). */
      if (scope == NULL) {
        /* This is not a definition.  Advance past the source sequence
           entries for types declared or defined in the function declarator. */
        bypass_prototype_scope_type_src_seq_entries();
      } else {
        /* This is a definition.  Advance past the source sequence entries for
           the parameters and any types declared or defined in the
           function declarator. */
        bypass_prototyped_param_src_seq_entries();
      }  /* if */
      for (;;) {
        if (scope != NULL) {
          /* This is the definition of the function, so put out the type and
             name from the parameter variable.  Note that the type in the
             variable might be slightly different than (though, of course,
             compatible with) the type in the param_type entry. */
          if (param_var->storage_class == (a_storage_class)sc_register) {
            gen_storage_class(param_var->storage_class);
          }  /* if */
          /* Watch out for unnamed parameters in C++. */
          gen_declaration_using_type(param_var->type,
                                     has_name(param_var) ?
                                             &param_var->source_corresp : NULL,
                                     iek_variable,
                                     (a_src_seq_secondary_decl_ptr)NULL);
          param_var = param_var->next;
        } else {
          /* This is just a declaration, so put out the type and no name. */
          gen_declaration_using_type(param->type, NO_NAME, iek_none,
                                     (a_src_seq_secondary_decl_ptr)NULL);
        }  /* if */
        /* Put out a default argument expression if there is one. */
        if (param->default_arg_expr != NULL) {
          write_tok_str(" = ");
          gen_initializer_expr(param->default_arg_expr, param->type,
                               /*need_parens=*/TRUE);
        }  /* if */
        param = param->next;
        if (param == NULL) break;
        /* There are more parameters, so output a separator and keep
           looping. */
        write_tok_str(", ");
      }  /* for */
    }  /* if */
    if (rtsp->has_ellipsis) {
      /* There is an ellipsis. */
      /* Separate it from the parameters if there are any. */
      if (rtsp->param_type_list != NULL) write_tok_str(", ");
      write_tok_str("...");
    }  /* if */
  }  /* if */
  write_tok_ch(')');
  /* Output a cv-qualifier for a member function, if there is one. */
  if (rtsp->implicit_this_param_type != NULL) {
    a_type_ptr           underlying_type =
                               type_pointed_to(rtsp->implicit_this_param_type);
    a_type_qualifier_set qualifiers = get_type_qualifiers(underlying_type);
    if (qualifiers != TQ_NONE) {
      write_space();
      form_type_qualifier(qualifiers, /*need_trailing_space=*/FALSE, &octl);
    }  /* if */
  }  /* if */
}  /* gen_function_declarator_with_scope */


static void gen_function_declarator(a_type_ptr type)
/*
Output a function declarator for the indicated routine type.  This is
not a function definition.  This routine is used as an interface to the
il_to_str routines.
*/
{
  gen_function_declarator_with_scope(type, (a_scope_ptr)NULL);
}  /* gen_function_declarator */


static void gen_type(a_type_ptr type)
/*
Output a reference to a type.
*/
{
  form_type(type, &octl);
}  /* gen_type */


static void set_decl_position(a_source_correspondence      *scp,
                              a_src_seq_secondary_decl_ptr sec_decl)
/*
Position the output file properly for the declaration position indicated
in the given source correspondence, or in the secondary declaration
entry if sec_decl is non-NULL.
*/
{
  a_source_position *eff_pos;

  if (sec_decl != NULL) {
    /* This is a secondary declaration, so use the position in the secondary
       declaration entry. */
    eff_pos = &sec_decl->decl_position;
  } else {
    /* Normal case -- use the position in the source correspondence. */
    eff_pos = &scp->decl_position;
  }  /* if */
  /* Adjust the output file to the right position. */
  set_output_position(eff_pos);
}  /* set_decl_position */


static void gen_declaration_using_type(a_type_ptr                   type,
                                       a_source_correspondence      *scp,
                                       an_il_entry_kind             entry_kind,
                                       a_src_seq_secondary_decl_ptr sec_decl)
/*
Output a declaration built around a type.  The argument scp is the source
correspondence entry for the entity being declared, or NULL if there is
no name.  entry_kind indicate the IL entry kind (it is ignored if
scp is NULL).  If sec_decl is non-NULL, this declaration is a secondary
declaration of the entity, and sec_decl points to information about the
secondary declaration.
*/
{
  /* Write the specifiers and the first part of the declarator. */
  form_type_first_part_simple(type, /*under_lhs_declarator=*/FALSE,
                              /*need_trailing_space=*/(scp != NULL),
                              &octl);
  /* Write the name if there is one. */
  if (scp != NULL) {
    /* Set the source position for the name. */
    set_decl_position(scp, sec_decl);
    /* Write the name. */
    gen_decl_name(scp, entry_kind);
    /* Push the name context class(es) for a class member. */
    push_class_name_context_if_member(scp);
  }  /* if */
  /* Write the second part of the declarator. */
  form_type_second_part_simple(type, /*under_lhs_declarator=*/FALSE, &octl);
  /* Pop the name context class(es) for a class member. */
  if (scp != NULL) pop_class_name_context_if_member(scp);
}  /* gen_declaration_using_type */


static void gen_enum_definition(a_type_ptr type)
/*
Output the definition of the indicated enum type.  This is in the form of
a type specifier (no trailing ";").  The current source sequence entry
is the one associated with the definition of the enum.
*/
{
  a_constant_ptr enum_con;
  a_constant     next_enum_value;

  check_assertion_str(type->kind == (a_type_kind)tk_enum &&
                      type->variant.integer.enum_type,
                      "gen_enum_definition: not an enum type");
  type->declaration_put_out = TRUE;
  /* Advance past the source sequence entry for the enum itself. */
  check_for_and_take_source_seq_entry(
                                   type->source_corresp.source_sequence_entry);
  /* Position the output file to the definition position. */
  set_output_position(&type->source_corresp.decl_position);
  /* Generate "enum <name>". */
  write_tok_str("enum ");
  /* (Note that a name will be generated for an unnamed enum.  That's
     necessary in C mode to allow the necessary casts of enumerator
     constants, and it's not a bad thing in general.) */
  gen_decl_name(&type->source_corresp, iek_type);
  write_tok_str(" { ");
  enum_con = type->variant.integer.enum_info.constant_list;
  if (enum_con != NULL) {
    /* Output the enumeration constants. */
    /* Start with an expected value of 0 next. */
    next_enum_value = *enum_con;
    set_integer_value(&next_enum_value.variant.integer_value, 0L);
    for (;;) {
      /* The source sequence entry for the enum constant should be next. */
      check_for_and_take_source_seq_entry(
                               enum_con->source_corresp.source_sequence_entry);
      set_output_position(&enum_con->source_corresp.decl_position);
      /* Output the constant's name. */
      gen_decl_name(&enum_con->source_corresp, iek_constant);
      /* Output the value if it's not the next value in sequence. */
      if (cmp_integer_constants(enum_con, &next_enum_value) != 0) {
        write_tok_str(" = ");
        write_tok_str(str_for_integer_constant(enum_con));
        next_enum_value = *enum_con;
      }  /* if */
      enum_con = enum_con->next;
      /* Stop if at the end of the list of constants. */
      if (enum_con == NULL) break;
      /* Not the end of the list, so output a separator and keep looping. */
      write_tok_str(", ");
      incr_integer_value(&next_enum_value.variant.integer_value);
      /* Skip any type declarations in the expression following an
         enumerator, as in
           enum E { e1, e2 = sizeof(struct A *) };
      */
      skip_embedded_declarations();
    }  /* for */
  }  /* if */
  /* The current source sequence entry should now be the end-of-construct
     marker for the enum. */
  { a_src_seq_end_of_construct_ptr ssecp =
                                  ss_entry_ptr(curr_source_sequence_entry,
                                               a_src_seq_end_of_construct_ptr);
    check_assertion_str(ss_entry_kind(ssecp) == iek_type &&
                        ss_entry_ptr(ssecp, a_type_ptr) == type,
                        "gen_enum_definition: bad end-of-construct");
    /* Set the position for the closing "}". */
    set_output_position(&ssecp->source_position);
    adv_curr_source_sequence_entry();
  }
  write_tok_ch('}');
}  /* gen_enum_definition */


static void gen_access_specifier(an_access_specifier access)
/*
Write the string that corresponds to the indicated access specifier value.
*/
{
  char *s;

  switch (access) {
    case as_public:     s = "public";    break;
    case as_protected:  s = "protected"; break;
    case as_private:    s = "private";   break;
    default:            unexpected_condition();
  }  /* switch */
  write_tok_str(s);
}  /* gen_access_specifier */


static void gen_member_access_specifier(an_access_specifier access)
/*
Generate an access specifier in a class definition to change the current
access mode to the indicated access.  Do nothing if the current access
is already set to that value.
*/
{
  if (access != curr_name_context->access) {
    /* The desired access is not the current access, so put out an access
       specifier, e.g., "public:". */
    gen_access_specifier(access);
    write_tok_ch(':');
    write_space();
    curr_name_context->access = access;
  }  /* if */
}  /* gen_member_access_specifier */


static void gen_member_access_specifier_for_decl_of(
                                                  a_source_correspondence *scp)
/*
A declaration or definition of the entity whose source correspondence
information is given by scp is about to be put out.  If we are currently
generating a class definition, and the entity is a member of the class,
output an access specifier (e.g., "public:") if necessary to set the
current access mode in the class.  Otherwise, do nothing.
*/
{
  if (curr_name_context_is_a_class() &&
      scp->class_of_which_a_member == curr_name_context_class()) {
    /* We're inside a class, and the entity being output is a member of that
       class. */
    gen_member_access_specifier((an_access_specifier)scp->access);
  }  /* if */
}  /* gen_member_access_specifier_for_decl_of */


static void gen_member_constant_decl(void)
/*
Generate a declaration for a member constant (an extension).  The current
source sequence entry is the one associated with the constant.
*/
{
  a_constant_ptr constant =
                      ss_entry_ptr(curr_source_sequence_entry, a_constant_ptr);

  /* Advance past the source sequence entry for the constant. */
  adv_curr_source_sequence_entry();
  set_output_position(&constant->source_corresp.decl_position);
  gen_member_access_specifier_for_decl_of(&constant->source_corresp);
  /* Generate the constant type and name.  The type must be generated specially
     with an extra "const" on top, since the const is removed in the
     constant type. */
  form_type_first_part(constant->type,
                       /*under_lhs_declarator=*/FALSE,
                       /*need_trailing_space=*/TRUE,
                       TQ_CONST, FTO_NO_OPTIONS, &octl);
  /* Set the source position for the name. */
  set_output_position(&constant->source_corresp.decl_position);
  /* Write the name. */
  gen_decl_name(&constant->source_corresp, iek_constant);
  /* Write the second part of the declarator. */
  form_type_second_part_simple(constant->type, /*under_lhs_declarator=*/FALSE,
                               &octl);
  write_tok_str(" = ");
  /* Generate the constant value. */
  gen_constant(constant, /*need_parens=*/FALSE);
  write_tok_ch(';');
  write_space();
}  /* gen_member_constant_decl */


static void gen_field_decl(void)
/*
Generate the declaration for a field (a nonstatic data member).  The current
source sequence entry is the one associated with the field.
*/
{
  a_field_ptr field = ss_entry_ptr(curr_source_sequence_entry, a_field_ptr);

  /* Advance past the source sequence entry for the field. */
  adv_curr_source_sequence_entry();
  set_output_position(&field->source_corresp.decl_position);
  gen_member_access_specifier_for_decl_of(&field->source_corresp);
  /* Generate the field type and name.  No name is displayed for unnamed
     bit fields and anonymous union fields. */
  gen_declaration_using_type(field->type,
                             has_name(field) ? &field->source_corresp : NULL,
                             iek_field,
                             (a_src_seq_secondary_decl_ptr)NULL);
  if (field->is_bit_field) {
    /* A bit field.  Put out the size. */
    write_tok_ch(':');
    write_unsigned_num((unsigned long)field->bit_size);
  }  /* if */
  write_tok_ch(';');
  write_space();
}  /* gen_field_decl */


static void gen_access_adjustment(void)
/*
Generate an access adjustment declaration.  The current source sequence
entry is the one associated with the access adjustment.
*/
{
  an_access_adjustment_ptr adj = ss_entry_ptr(curr_source_sequence_entry,
                                              an_access_adjustment_ptr);
  a_source_correspondence  *scp = NULL;
  an_il_entry_kind         entry_kind;

  /* Advance past the source sequence entry for the adjustment. */
  adv_curr_source_sequence_entry();
  /* Put out an access specifier if necessary to change the current access. */
  gen_member_access_specifier(adj->access);
  entry_kind = (an_il_entry_kind)adj->entity.kind;
  /* Get the source correspondence entry for the entity. */
  switch (entry_kind) {
    case iek_field:
      scp = &((a_field_ptr)adj->entity.ptr)->source_corresp;
      break;
    case iek_variable:
      scp = &((a_variable_ptr)adj->entity.ptr)->source_corresp;
      break;
    case iek_routine:
      scp = &((a_routine_ptr)adj->entity.ptr)->source_corresp;
      break;
    case iek_type:
      scp = &((a_type_ptr)adj->entity.ptr)->source_corresp;
      break;
    case iek_constant:
      scp = &((a_type_ptr)adj->entity.ptr)->source_corresp;
      break;
    default:
      unexpected_condition();
  }  /* switch */
  /* Write the access declaration, which is just a qualified name. */
  gen_qualified_name(scp, entry_kind);
  write_tok_ch(';');
  write_space();
  /* For overloaded functions, there is an access adjustment and a source
     sequence entry for each function in the set.  If that is the case here,
     advance over the other entries. */
  if (entry_kind == (an_il_entry_kind)iek_routine) {
    while (curr_source_sequence_entry != NULL &&
           ss_entry_kind(curr_source_sequence_entry) == iek_access_adjustment){
      an_access_adjustment_ptr adjb = ss_entry_ptr(curr_source_sequence_entry,
                                                   an_access_adjustment_ptr);
      /* Keep going on access adjustments for routines with the same name. */
      if ((an_il_entry_kind)adjb->entity.kind != iek_routine ||
          ((a_routine_ptr)adjb->entity.ptr)->source_corresp.name !=
                  ((a_routine_ptr)adj->entity.ptr)->source_corresp.name) break;
      /* Advance past the source sequence entry for the adjustment. */
      adv_curr_source_sequence_entry();
    }  /* while */  
  }  /* if */
}  /* gen_access_adjustment */


static void gen_class_definition(a_type_ptr type)
/*
Output the definition of the indicated class type.  This is in the form of
a type specifier (no trailing ";").  The current source sequence entry
is the one associated with the definition of the class.
*/
{
  a_class_type_supplement_ptr ctsp =
                                   type->variant.class_struct_union.extra_info;
#if USER_CONTROL_OF_STRUCT_PACKING
  a_targ_alignment  pack_alignment = type->variant.class_struct_union.
                                                       max_member_alignment;

  /* If required, put out a #pragma pack directive to set the pack
     alignment for the current class. */
  if (pack_alignment > 0) {
    if (pack_alignment == il_header.default_max_member_alignment) {
      /* No need to put out a pragma to override the default value. */
      pack_alignment = 0;
    } else {
      /* Put out a #pragma pack directive to indicate the special alignment
         requirements for this struct. */
      end_output_line_if_begun();
      disable_line_wrapping();
      write_str("#pragma pack(");
      write_unsigned_num(pack_alignment);
      write_str(")");
      enable_line_wrapping();
      end_output_line();
    }  /* if */
  }  /* if */
#endif /* USER_CONTROL_OF_STRUCT_PACKING */
  type->declaration_put_out = TRUE;
  /* Advance past the source sequence entry for the class itself. */
  check_for_and_take_source_seq_entry(
                                   type->source_corresp.source_sequence_entry);
  /* Position the output file to the definition position. */
  set_output_position(&type->source_corresp.decl_position);
  if (ctsp != NULL &&
      ctsp->anonymous_union_kind == (an_anonymous_union_kind)auk_variable) {
    /* For a global anonymous union, put out "static" in front of the union. */
    write_tok_str("static ");
  }  /* if */
  write_tok_str(tag_kind(type->kind));
  /* Write the name of the class. */
  if (ctsp != NULL &&
      ctsp->anonymous_union_kind != (an_anonymous_union_kind)auk_none) {
    /* The type is an anonymous union, so suppress the name. */
  } else if (type->variant.class_struct_union.originally_unnamed &&
             has_name(type)) {
    /* The type was unnamed but got a name from a typedef, so suppress the
       name here.  For example:
         typedef struct { int A; } A;
    */
  } else {
    /* Put out the name.  Note that a name will be generated for an
       unnamed class, which can be useful for casts. */
    write_space();
    gen_decl_name(&type->source_corresp, iek_type);
  }  /* if */
  /* Put out the class definition. */
  if (il_header.source_language == sl_Cplusplus) {
    /* Put out the base class list. */
    a_base_class_ptr bcp = ctsp->base_classes;
    a_boolean        first_base_class = TRUE;
    if (bcp != NULL) {
      write_tok_str(" : ");
      for (; bcp != NULL; bcp = bcp->next) {
        /* The list contains all base classes, but put out only the direct
           base classes. */
        if (bcp->direct) {
          a_base_class_derivation_ptr bcdp = bcp->derivation;
          /* If this is not the first base class, put a comma between the
             base classes. */
          if (!first_base_class) write_tok_str(", ");
          first_base_class = FALSE;
          if (bcp->is_virtual) {
            write_tok_str("virtual ");
            /* Find the direct derivation for a virtual base class. */
            for (; !bcdp->direct; bcdp = bcdp->next) {}
          }  /* if */
          /* Display the derivation access. */
          gen_access_specifier(bcdp->access);
          write_space();
          gen_type_name(bcp->type);
        }  /* if */
      }  /* for */
    }  /* if */
  }  /* if */
  write_tok_str(" { ");
  if (il_header.source_language == sl_Cplusplus) {
    push_name_context(ctsp->assoc_scope);
    /* Keep track of the current access category, in order to emit a change
       when necessary. */
    if (ctsp->anonymous_union_kind == (an_anonymous_union_kind)auk_field) {
      /* An anonymous union starts with the same access as the enclosing
         class. */
      curr_name_context->access = curr_name_context->next->access;
    } else {
      /* Normal case (not an anonymous union).  Start with the default
         based on the class/struct/union keyword. */
      curr_name_context->access = (an_access_specifier)as_public;
      if (type->kind == (a_type_kind)tk_class) {
        curr_name_context->access = (an_access_specifier)as_private;
      }  /* if */
    }  /* if */
  }  /* if */
  /* Go through the source sequence list and generate the members of the
     class. */
  for (;;) {
    switch (ss_entry_kind(curr_source_sequence_entry)) {
      case iek_src_seq_end_of_construct:
        /* This should be the end-of-construct marker for the class. */
        { a_src_seq_end_of_construct_ptr ssecp = 
                                  ss_entry_ptr(curr_source_sequence_entry,
                                               a_src_seq_end_of_construct_ptr);
          check_assertion_str(ss_entry_kind(ssecp) == iek_type &&
                              ss_entry_ptr(ssecp, a_type_ptr) == type,
                              "gen_class_definition: bad end-of-construct");
          /* Set the position for the closing "}". */
          set_output_position(&ssecp->source_position);
          adv_curr_source_sequence_entry();
        }
        /* End the loop. */
        goto done;
      case iek_constant:
        /* C++ member constant. */
        gen_member_constant_decl();
        break;
      case iek_field:
        /* Generate the declaration for a field (nonstatic data member). */
        gen_field_decl();
        break;
      case iek_type:
        /* Nested type. */
        gen_type_decl();
        break;
      case iek_variable:
        /* Static data member. */
        gen_variable_decl();
        break;
      case iek_routine:
        /* Member function */
        gen_routine_decl();
        break;
      case iek_pragma:
        gen_pragma();
        break;
#if RECORD_MACROS_IN_IL
      case iek_macro:
        gen_macro();
        break;
#endif /* RECORD_MACROS_IN_IL */
      case iek_src_seq_secondary_decl:
        /* A secondary declaration, i.e., a declaration of something that
           is also defined/declared elsewhere. */
        gen_secondary_decl();
        break;
      case iek_access_adjustment:
        gen_access_adjustment();
        break;
      default:
        unexpected_condition_str("gen_class_definition: bad entity kind");
    }  /* switch */
  }  /* for */
done:;
  if (il_header.source_language == sl_Cplusplus) pop_name_context();
  write_tok_ch('}');
#if USER_CONTROL_OF_STRUCT_PACKING
  if (pack_alignment > 0) {
    /* Restore the packing alignment to a default state. */
    end_output_line_if_begun();
    disable_line_wrapping();
    write_str("#pragma pack()");
    enable_line_wrapping();
    end_output_line();
  }  /* if */
#endif /* USER_CONTROL_OF_STRUCT_PACKING */
}  /* gen_class_definition */


static void gen_typedef_definition(a_type_ptr                   type,
                                   a_src_seq_secondary_decl_ptr sec_decl)
/*
Output the definition of the indicated typedef (without a trailing ";").
The current source sequence entry is the one associated with the definition
of the typedef.  If it is a secondary declaration (C++ only), sec_decl
is non-NULL and points to the secondary declaration entry.
*/
{
  a_type_ptr under_type, this_param_type;

  if (sec_decl != NULL) {
    /* Use the type from the secondary declaration entry instead of the one
       from the IL entry, since it might differ in small ways (e.g., using
       different typedefs, default arguments). */
    under_type = sec_decl->declared_type;
  } else {
    under_type = type->variant.typeref.type;
  }  /* if */
  /* Advance past the source sequence entry for the typedef itself. */
  /* This does not use check_for_and_take_source_seq_entry on purpose,
     because in C++ there can be more than one definition of the typedef
     and this routine is called for each one. */
  adv_curr_source_sequence_entry();
  /* The caller has called set_decl_position already. */
  write_tok_str("typedef ");
  if (is_function_type(under_type) &&
      (this_param_type = implicit_this_param_type_of(under_type)) != NULL) {
    /* A cfront member function typedef, e.g.,
         typedef int A::f(int);
       Put out with a qualified name. */
    a_type_ptr class_type = f_skip_typerefs(type_pointed_to(this_param_type));
    form_type_first_part_simple(under_type, /*under_lhs_declarator=*/FALSE,
                                /*need_trailing_space=*/TRUE, &octl);
    /* Write the (qualified) name. */
    gen_class_qualifier(class_type);
    gen_unqualified_name(&type->source_corresp, iek_type);
    /* Write the second part of the declarator. */
    form_type_second_part_simple(under_type, /*under_lhs_declarator=*/FALSE,
                                 &octl);
  } else {
    /* Normal typedef. */
    gen_declaration_using_type(under_type, &type->source_corresp,
                               iek_type, sec_decl);
  }  /* if */
}  /* gen_typedef_definition */


static a_boolean is_on_friend_list_of(a_type_ptr type,
                                      a_type_ptr friend_type)
/*
Return TRUE if friend_type is a friend of the class type "type".
*/
{
  a_boolean              is_friend = FALSE;
  a_class_list_entry_ptr pfriend;

  for (pfriend = type->variant.class_struct_union.extra_info->friend_classes;
       pfriend != NULL;
       pfriend = pfriend->next) {
    if (pfriend->class_type == friend_type) {
      is_friend = TRUE;
      break;
    }  /* if */
  }  /* for */
  return is_friend;
}  /* is_on_friend_list_of */


static void gen_class_friend_prefix_if_needed(a_type_ptr type)
/*
A declaration (not definition) of the indicated type is being put out.
If the declaration is a friend class declaration, put out the "friend"
prefix.  Called only in C++ mode.
*/
{
  a_boolean friend_decl = FALSE;

  if (curr_name_context_is_a_class()) {
    /* This declaration is inside a class. */
    a_type_ptr class_type = type->source_corresp.class_of_which_a_member;
    if (curr_name_context_class() == class_type) {
      /* This is a declaration of a nested class inside the class of
         which it is a member.  It's probably just the declaration of
         a nested type, but it might still be a friend declaration:
           struct A {
             struct B { int i; };
             friend struct B;  // This line
            };
      */
      if (is_on_friend_list_of(class_type, type)) {
        /* Put out a vacuous declaration of the class, and then
           start a friend declaration.  Using two declarations is
           necessary because "friend class B;" as the first appearance
           would put B outside of the class A, and we can't easily
           tell if this is the first appearance of the class. */
        gen_tag_reference(type);
        write_tok_ch(';');
        write_space();
        friend_decl = TRUE;
      }  /* if */
    } else {
      /* This is a declaration of a nested type outside of the class
         of which it is a member but inside some other class, or a
         declaration of a nonmember class inside some class.  This
         must be a friend declaration. */
      friend_decl = TRUE;
    }  /* if */
  }  /* if */
  if (friend_decl) write_tok_str("friend ");
}  /* gen_class_friend_prefix_if_needed */


static void gen_type_decl(void)
/*
Generate a declaration or definition of the type indicated by the current
source sequence entry.  This might be a declaration or definition of
a member type, nonmember type, or friend.
*/
{
  a_type_ptr                   type;
  a_src_seq_secondary_decl_ptr sec_decl;
  a_type_kind                  kind ;
  a_boolean                    is_definition = FALSE;

  /* Deal with the primary/secondary declaration difference. */
  if (curr_src_seq_entry_is_secondary_decl(&sec_decl)) {
    type = ss_entry_ptr(sec_decl, a_type_ptr);
  } else {
    type = ss_entry_ptr(curr_source_sequence_entry, a_type_ptr);
    is_definition = TRUE;
  }  /* if */
  kind = type->kind;
  if (!is_autonomous_decl(type, sec_decl)) {
    /* This type declaration is embedded in another declaration.
       Do not put it out at this time.  Mark it for processing when
       it is encountered while traversing the IL tree. */
    skip_type_and_delay_definition(type, is_definition);
  } else {
    /* Set the output position. */
    set_decl_position(&type->source_corresp, sec_decl);
    /* If generating a member of a class within the class, set the right access
       mode for the member. */
    gen_member_access_specifier_for_decl_of(&type->source_corresp);
    if (kind == (a_type_kind)tk_typeref) {
      /* A typedef definition. */
      gen_typedef_definition(type, sec_decl);
    } else if (!is_definition) {
      /* For a secondary declaration, or a primary declaration of a type
         that is never defined, generate a reference to the type instead
         of a definition. */
      adv_curr_source_sequence_entry();
      if (il_header.source_language == sl_Cplusplus) {
        /* Check for friend declarations. */
        gen_class_friend_prefix_if_needed(type);
      }  /* if */
      gen_tag_reference(type);
    } else if (kind == (a_type_kind)tk_enum) {
      /* An enum type definition. */
      gen_enum_definition(type);
    } else {
      check_assertion_str(is_class_type_kind(kind),
                          "gen_type_decl: bad type on list");
      /* A class type definition. */
      gen_class_definition(type);
    }  /* if */
    /* Finish the declaration. */
    write_tok_ch(';');
    write_space();
  }  /* if */
}  /* gen_type_decl */


static void gen_ampersand(a_type_ptr type)
/*
Output an ampersand to indicate taking the address of something.  However,
if the something (which has type "type") is an array or function, suppress
the ampersand since C will assume one.
*/
{
  if (is_function_type(type)) {
    /* No ampersand needed. */
  } else if (il_header.pcc_compatibility_mode && is_array_type(type)) {
    /* pcc C compilers don't like ampersands in front of arrays.  However,
       the address we want here must have type "pointer-to-array", and
       the implicit decay to pointer will give "pointer-to-array-element",
       so cast the decayed pointer to the right type. */
    write_tok_ch('(');
    /* Write the specifiers and the first part of the declarator. */
    form_type_first_part_simple(type, /*under_lhs_declarator=*/TRUE,
                               /*need_trailing_space=*/FALSE, &octl);
    /* Add an extra "pointer-to". */
    write_tok_ch('*');
    /* Write the second part of the declarator. */
    form_type_second_part_simple(type, /*under_lhs_declarator=*/TRUE,
                                 &octl);
    write_tok_ch(')');
  } else {
    write_tok_ch('&');
  }  /* if */
}  /* gen_ampersand */


static an_expr_node_ptr optimized_expr_for_selection(
                                                an_expr_node_ptr object_expr,
                                                a_type_ptr       *naming_class)
/*
object_expr is an expression that gives the address of a class object.
It is being used as the address for a member selection.  Examine the
base-class casts on the object, if there are any, and determine which
of those can be folded into the member name.  Return the expression to
be used to address the object (the part not including the casts that
can be elided), and set *naming_class to the class qualifier name
to be used to name the member.  Only used in C++.
*/
{
  an_expr_node_ptr node = object_expr, naming_node = NULL;

  /* An example will help:

       struct A { int i; };
       struct B : public A {};
       struct C : public B {} c;
       {  .... c.B::i ... }

           eok_field
             /   \___________________________ field A::i
            /
        Cast to A * (implicit_in_member_naming == TRUE)    (1)
            |
            V
        Cast to B *                                        (2)
            |
            V
        Addr of c                                          (3)

     Expression (1) is given to this routine.  Node (1) is passed over
     because it is implicit in the naming.  Node (2) is also passed over,
     but since it is not implicit in the naming, *naming_class is set
     to class B.  Node (3) is returned. */
  while (is_operation_node(node) &&
         node->variant.operation.kind ==
                                  (an_expr_operator_kind)eok_base_class_cast &&
         node->variant.operation.compiler_generated) {
    if (!node->variant.operation.implicit_in_member_naming &&
        naming_node == NULL) {
      /* Remember the first node after the casts implied by naming. */
      naming_node = node;
    }  /* if */
    node = node->variant.operation.operands;
  }  /* while */
  /* If there were no base class casts, or none not implied by naming,
     the final node is used to determine the selection class. */
  if (naming_node == NULL) naming_node = node;
  /* Fetch the class type to be used to name the member. */
  *naming_class = f_skip_typerefs(type_pointed_to(naming_node->type));
  return node;
}  /* optimized_expr_for_selection */


static void gen_field_reference(an_expr_node_ptr node)
/*
Generate the name of the field from the indicated node (an enk_field node).
*/
{
  a_field_ptr field;

  check_assertion_str(node->kind == (an_expr_node_kind)enk_field,
                      "gen_field_reference: not enk_field");
  field = node->variant.field;
  /* Put out the (unqualified) field name. */
  gen_field_name(field);
}  /* gen_field_reference */


static void gen_simple_field_selection(an_expr_node_ptr object_expr,
                                       an_expr_node_ptr field_expr)
/*
Generate "object_expr . field_expr".  object_expr is an address (or lvalue),
and field_expr is an enk_field node.
*/
{
  a_type_ptr naming_class, selection_class;

  if (il_header.source_language == sl_Cplusplus) {
    /* Remove unnecessary base class casts. */
    object_expr = optimized_expr_for_selection(object_expr, &naming_class);
  }  /* if */
  if (object_expr->kind == (an_expr_node_kind)enk_variable) {
    /* Optimize "(*p).i" as "p->i". */
    gen_expression(object_expr);
    write_tok_str("->");
  } else if (object_expr->kind == (an_expr_node_kind)enk_variable_address &&
             object_expr->variant.variable->is_anonymous_parent_object) {
    /* For an anonymous union variable, do not put out the variable or "."
       at all. */
  } else {
    /* Normal "." case. */
    gen_lvalue(object_expr);
    m_write_tok_ch('.');
  }  /* if */
  if (il_header.source_language == sl_Cplusplus) {
    /* Use a qualified name if the class in which we want to name the member
       is not the class indicated by the pointer. */
    selection_class = type_pointed_to(object_expr->type);
    selection_class = skip_typerefs(selection_class);
    if (selection_class != naming_class) gen_class_qualifier(naming_class);
  }  /* if */
  gen_field_reference(field_expr);
}  /* gen_simple_field_selection */


static void gen_temp_init(an_expr_node_ptr expr)
/*
Generate code for an enk_temp_init node, which does creation/initialization
of a temporary in an expression.  The caller should check whether the
result_is_addr flag is set correctly; this routine cannot deal with that.
*/
{
  a_dynamic_init_ptr dip = expr->variant.init.dynamic_init;

  if (dip->kind == (a_dynamic_init_kind)dik_constructor ||
      dip->kind == (a_dynamic_init_kind)dik_zero) {
    /* For a class temporary requiring a constructor, use the form
       A(arg1, arg2, ...).  dik_zero is for cases like "A()". */
    /* Note that parentheses are not put around this, because that would
       make the expression look like a cast. */
    a_type_ptr temp_type = expr->type;
    if (expr->variant.init.result_is_addr) {
      temp_type = type_pointed_to(temp_type);
    }  /* if */
    /* Right now, dik_zero is only used for class types, and rvalues have
       no type qualifiers. */
    check_assertion_str(is_immediate_class_type(temp_type),
                        "gen_temp_init: temp type not class");
    gen_type_name(temp_type);
    gen_dynamic_init(dip,
                     (a_type_ptr)NULL, /* Not a reference, not needed. */
                     /*parenthesized_init=*/TRUE,
                     /*force_parens=*/TRUE);
  } else {
    /* Other cases -- just put out the value. */
    gen_dynamic_init(dip,
                     (a_type_ptr)NULL, /* Not a reference, not needed. */
                     /*parenthesized_init=*/FALSE,
                     /*force_parens=*/FALSE);
  }  /* if */
}  /* gen_temp_init */


static void gen_lvalue(an_expr_node_ptr node)
/*
Generate an expression that the IL sees as an lvalue address, and C sees as
an expression.  In effect, add an indirection to the expression.  The
expression is surrounded by parentheses if there's some possibility of
precedence confusion.
*/
{
  an_expr_node_kind kind = node->kind;
  a_boolean         processed = FALSE;

  if (node->implicit_reference_indirection) {
    /* This node includes an indirection for a C++ reference type.
       That is, there's an indirection that's explicit in the IL but is
       implicit in the source.  That cancels out the indirection we
       would be adding in the source relative to what's in the IL, so
       just put out the expression. */
    node->implicit_reference_indirection = FALSE;
    gen_expr_with_parens(node);
    node->implicit_reference_indirection = TRUE;
    processed = TRUE;
  } else if (kind == (an_expr_node_kind)enk_variable_address) {
    /* Address of variable: just write the variable name. */
    gen_variable_name(node->variant.variable);
    processed = TRUE;
  } else if (kind == (an_expr_node_kind)enk_routine_address) {
    /* Address of routine: just write the routine name. */
    gen_routine_name(node->variant.routine);
    processed = TRUE;
  } else if (kind == (an_expr_node_kind)enk_operation) {
    an_expr_operator_kind op = node->variant.operation.kind;
    an_expr_node_ptr      operand_1 = node->variant.operation.operands;
    an_expr_node_ptr      operand_2 = operand_1->next;
    if (op == (an_expr_operator_kind)eok_padd ||
        op == (an_expr_operator_kind)eok_padd_subsc) {
      /* The expression is a pointer addition.  It can be rewritten as
         a subscripting operation (i.e., *(a+b) becomes a[b]). */
      write_tok_ch('(');
      gen_expr_with_parens(operand_1);
      write_tok_ch('[');
      gen_expression(operand_2);
      write_tok_str("])");
      processed = TRUE;
    } else if (op == (an_expr_operator_kind)eok_field ||
               op == (an_expr_operator_kind)eok_bit_field) {
      /* The expression is a field selection, which has an implicit "&"
         in front of it (in C terms).  Adding the indirection removes 
         the "&". */
      write_tok_ch('(');
      gen_simple_field_selection(operand_1, operand_2);
      write_tok_ch(')');
      processed = TRUE;
    } else if (node->variant.operation.returns_lvalue_instead_of_usual_rvalue){
      /* An operation that returns an lvalue, e.g., an lvalue-returning
         assignment.  Just put the expression out. */
      gen_expr_with_parens(node);
      processed = TRUE;
    }  /* if */
  } else if (kind == (an_expr_node_kind)enk_temp_init &&
             node->variant.init.result_is_addr) {
    /* A temporary initialization with the address of the temporary used as
       the node value.  Just put out the underlying value. */
    gen_temp_init(node);
    processed = TRUE;
  }  /* if */
  if (!processed) {
    /* Not a special case: write "*expression". */
    write_tok_str("(*");
    gen_expr_with_parens(node);
    write_tok_ch(')');
  }  /* if */
}  /* gen_lvalue */


static an_expr_node_ptr skip_implicit_ptr_type_qualifier_adjustment_cast(
                                                         an_expr_node_ptr expr)
/*
Remove any implicit casts on the top of the expression that merely adjust
the type qualifiers on a pointer type (e.g., add const), and return the
underlying expression.
*/
{
try_again:
  if (is_operation_node(expr) &&
      expr->variant.operation.kind == (an_expr_operator_kind)eok_cast &&
      expr->variant.operation.compiler_generated) {
    a_type_ptr dest_type = expr->type;
    a_type_ptr source_type = expr->variant.operation.operands->type;
    if (is_pointer_type(dest_type) && is_pointer_type(source_type)) {
      dest_type = type_pointed_to(dest_type);
      source_type = type_pointed_to(source_type);
      if (skip_typerefs(dest_type) == skip_typerefs(source_type)) {
        /* The underlying types are the same ignoring qualifiers.  Since
           this is an implicit cast, the qualifiers must be the same or
           must increase with the cast. */
        /* This is a cast that just adjusts the type qualifiers. */
        expr = expr->variant.operation.operands;
        goto try_again;
      }  /* if */
    }  /* if */
  }  /* if */
  return expr;
}  /* skip_implicit_ptr_type_qualifier_adjustment_cast */


static void gen_initializer_expr(an_expr_node_ptr expr,
                                 a_type_ptr       type,
                                 a_boolean        need_parens)
/*
Generate an expression that is used to initialize something of type "type".
This does special processing when the type is a reference type.
type may be NULL if it isn't a reference type.  Put parentheses around
the code if there's some possibility of precedence confusion and
need_parens is TRUE.
*/
{
  /* When initializing a reference, remove one level of indirection. */
  if (type != NULL && is_reference_type(type)) {
    /* Remove any cast that just adjusts the type qualifiers (e.g., adds
       const); it's implied by the context. */
    expr = skip_implicit_ptr_type_qualifier_adjustment_cast(expr);
    /* Remove any implicit base-class casts; they're implied by the context. */
    while (is_operation_node(expr) &&
           expr->variant.operation.kind ==
                                  (an_expr_operator_kind)eok_base_class_cast &&
           expr->variant.operation.compiler_generated) {
      expr = expr->variant.operation.operands;
    }  /* while */
    /* Put the expression out as an lvalue to remove a level of indirection. */
    gen_lvalue(expr);
  } else if (il_header.source_language == sl_C &&
             is_constant_node(expr) &&
             is_implicitly_cast_integral_constant(expr->variant.constant)) {
    /* An integral constant that can be implicitly converted to another
       type.  Put out with the conversion implicit.  This is important in
       the case where the type involves a prototype scope type that cannot
       be named here. */
    form_integer_constant(expr->variant.constant, /*suppress_cast=*/TRUE,
                          need_parens, &octl);
  } else {
    gen_expr(expr, need_parens);
  }  /* if */
}  /* gen_initializer_expr */


static void gen_cast(a_type_ptr type)
/*
Generate a cast to the indicated type.
*/
{
  m_write_tok_ch('(');
  gen_type(type);
  m_write_tok_ch(')');
}  /* gen_cast */


static void gen_argument_list(an_expr_node_ptr arg,
                              a_type_ptr       rout_type,
                              int              skip_num)
/*
Write out an argument list with surrounding parentheses.  rout_type is the
type of the routine being called.  If skip_num is non-zero, it indicates
the number of leading argument expressions not to put out (they're on the
arg list and the parameter list, and they're passed over, but nothing is
put out for them).
*/
{
  a_param_type_ptr              param;
  a_boolean                     skipped_argument;
  a_routine_type_supplement_ptr rtsp;

  rout_type = skip_typerefs(rout_type);
  rtsp = rout_type->variant.routine.extra_info;
  param = rtsp->param_type_list;
  write_tok_ch('(');
  for (; arg != NULL;) {
    skipped_argument = FALSE;
    if (skip_num > 0) {
      /* Skip an argument. */
      skipped_argument = TRUE;
      skip_num--;
    } else if (param != NULL && param->passed_via_copy_constructor) {
      /* For an argument passed using a copy constructor, optimize out
         the copy constructor reference. */
      check_assertion_str(arg->kind == (an_expr_node_kind)enk_temp_init,
                          "gen_argument_list: cctor arg not enk_temp_init");
      gen_dynamic_init(arg->variant.init.dynamic_init, param->type,
                       /*parenthesized_init=*/FALSE,
                       /*force_parens=*/FALSE);
    } else {
      /* Normal case. */
      if (param != NULL) {
        /* Parameter type known. */
        gen_initializer_expr(arg, param->type, /*need_parens=*/TRUE);
      } else {
        /* Parameter type not known. */
        gen_expr_with_parens(arg);
      }  /* if */
    }  /* if */
    arg = arg->next;
    if (arg != NULL) {
      if (!skipped_argument) write_tok_str(", ");
      if (param != NULL) param = param->next;
    }  /* if */
  }  /* for */
  write_tok_ch(')');
}  /* gen_argument_list */


static a_boolean num_elems_can_be_found_in_size_expr(
                                              an_expr_node_ptr size_expr,
                                              a_targ_size_t    elem_size,
                                              an_expr_node_ptr *num_elems_expr)
/*
size_expr is an expression that gives the size in bytes of an array for a
"new" operation.  elem_size gives the size in bytes of an element of the
array.  See if part or all of the size_expr expression represents the
number of elements (which is array-size divided by elem-size).  If so,
set *num_elems_expr to point to that expression, and return TRUE; if not,
return FALSE.
*/
{
  a_boolean found = FALSE;

  *num_elems_expr = NULL;
  if (elem_size == 1) {
    /* The element size is 1, so the original expression will do. */
    found = TRUE;
    *num_elems_expr = size_expr;
  } else {
    /* Look for the pattern "expr * elem-size" as the top operation of
       the expression.  If it's there, the left-hand expression is the
       number of elements.  (Why wouldn't it be there?  Well, one case
       where it isn't is a multi-dimensional array.) */
    if (is_operation_node(size_expr) &&
        size_expr->variant.operation.kind ==
                                        (an_expr_operator_kind)eok_imultiply) {
      an_expr_node_ptr operand_1 = size_expr->variant.operation.operands;
      an_expr_node_ptr operand_2 = operand_1->next;
      if (is_constant_node(operand_2)) {
        a_constant_ptr con = operand_2->variant.constant;
        if (con->kind == (a_constant_repr_kind)ck_integer &&
            cmpulit_integer_constant(con, (unsigned long)elem_size) == 0) {
          /* Yes, the expression is "operand_1 * elem-size", so operand_1
             is the number-of-elements expression. */
          found = TRUE;
          *num_elems_expr = operand_1;
        }  /* if */
      }  /* if */
    }  /* if */
  }  /* if */
  return found;
}  /* num_elems_can_be_found_in_size_expr */


static void gen_new_delete(an_expr_node_ptr expr)
/*
Generate code for a new or delete operation.
*/
{
  a_new_delete_supplement_ptr ndsp = expr->variant.new_delete;
  a_type_ptr                  type = ndsp->type, unqual_type;
  a_routine_ptr               routine = ndsp->routine;
  an_expr_node_ptr            arg = ndsp->arg;
  a_boolean                   need_type_parens;

  unqual_type = skip_typerefs(type);
  /* See if a global specifier "::" is needed on the new or delete. */
  if (is_class_type_kind(unqual_type->kind) &&
      /* Watch out for the case where the new/delete is folded into the
         constructor/destructor. */
      routine != NULL &&
      routine->source_corresp.class_of_which_a_member == NULL) {
    /* Not a class-specific new or delete routine, so put out "::". */
    write_tok_str("::");
  }  /* if */
  if (ndsp->is_new) {
    /* New.  The general form is
         :: new (arg2, arg3, ...) type(initializer)
       Everything except "new" and the type is optional. */
    write_tok_str("new ");
    if (arg->next != NULL) {
      /* More than one argument, so this is a "placement" new.  Put out
         arguments 2-n inside parentheses. */
      gen_argument_list(arg, routine->type, /*skip_num=*/1);
      write_space();
    }  /* if */
    /* The syntax for types here is limited; to get the full range of
       possibilities, one must put parentheses around the type.  Avoid the
       parens in some simple cases. */
    need_type_parens = TRUE;
    { a_type_ptr  temp_type = type;
      a_type_kind tkind;
      if (temp_type->kind == (a_type_kind)tk_array) {
        /* Allow one array level in a simple new type. */
        temp_type = temp_type->variant.array.element_type;
      }  /* while */
      tkind = temp_type->kind;
      if (tkind == (a_type_kind)tk_integer ||
          tkind == (a_type_kind)tk_float ||
          is_class_type_kind(tkind) ||
          (tkind == (a_type_kind)tk_typeref &&
           typeref_is_typedef(temp_type))) {
        /* Simple cases that don't need parentheses. */
        need_type_parens = FALSE;
      }  /* if */
    }
    if (need_type_parens) write_tok_ch('(');
    /* The type is easy to put out except when it is a variable-length array
       type. */
    if (unqual_type->size != 0) {
      /* Normal case. */
      gen_type(type);
    } else {
      /* Harder case: a variable-length array.  The first argument expression
         gives the size of the array, which is the number of elements times
         the size of each element.  Put out the first part of the type, the
         open bracket, the expression, and the close bracket. */
      a_type_ptr       elem_type;
      a_targ_size_t    elem_size;
      an_expr_node_ptr num_elems_expr;
      check_assertion_str(unqual_type->kind == (a_type_kind)tk_array,
                          "gen_new_delete: zero-sized type not array");
      elem_type = unqual_type->variant.array.element_type;
      elem_size = skip_typerefs(elem_type)->size;
      form_type_first_part_simple(elem_type,
                                  /*under_lhs_declarator=*/FALSE,
                                  /*need_trailing_space=*/TRUE,
                                  &octl);
      write_tok_ch('[');
      if (num_elems_can_be_found_in_size_expr(arg, elem_size,
                                              &num_elems_expr)) {
        /* Optimization -- the number of elements was found in the
           size expression, so just print that. */
        gen_expression(num_elems_expr);
      } else {
        /* Not the optimizable case. */
        /* Write the size expression divided by the size of each element. */
        gen_expr_with_parens(arg);
        write_tok_ch('/');
        write_unsigned_num(elem_size);
      }  /* if */
      write_tok_ch(']');
      form_type_second_part_simple(elem_type, /*under_lhs_declarator=*/FALSE,
                                   &octl);
    }  /* if */
    if (need_type_parens) write_tok_ch(')');
    if (ndsp->dynamic_init != NULL) {
      /* The allocated entity gets initialized. */
      gen_dynamic_init(ndsp->dynamic_init, type, /*parenthesized_init=*/TRUE,
                       /*force_parens=*/FALSE);
    }  /* if */
  } else {
    /* Delete.  The general form is
         :: delete [] expression
       Everything except "delete" and the expression is optional. */
    write_tok_str("delete ");
    if (ndsp->array_delete) write_tok_str("[] ");
    gen_expr_with_parens(arg);
  }  /* if */
}  /* gen_new_delete */


static void gen_bound_function(an_expr_node_ptr object_expr,
                               an_expr_node_ptr func_expr,
                               a_boolean        suppress_virtual)
/*
Generate "object->function", a bound function expression.
If suppress_virtual is TRUE, suppress virtual-ness on the function reference.
*/
{
  a_routine_ptr rout;
  a_type_ptr    naming_class, selection_class;

  /* Remove any cast that just adjusts the type qualifiers (e.g., adds
     const); it's implied by the context. */
  object_expr = skip_implicit_ptr_type_qualifier_adjustment_cast(object_expr);
  /* Remove unnecessary base class casts. */
  object_expr = optimized_expr_for_selection(object_expr, &naming_class);
  if (is_variable_node(object_expr)) {
    /* Use a pointer and "->". */
    gen_expr_with_parens(object_expr);
    write_tok_str("->");
  } else {
    /* Use an lvalue and ".". */
    gen_lvalue(object_expr);
    write_tok_ch('.');
  }  /* if */
  check_assertion(func_expr->kind == (an_expr_node_kind)enk_routine_address);
  rout = func_expr->variant.routine;
  if (suppress_virtual && rout->is_virtual) {
    /* The routine being called is a virtual function, and we're supposed
       to suppress its virtual-ness in this call, so use a qualified name. */
    gen_qualified_name(&rout->source_corresp, iek_routine);
  } else {
    /* Normal case. */
    /* Use a qualified name if the class in which we want to name the member
       is not the class indicated by the pointer. */
    selection_class = type_pointed_to(object_expr->type);
    selection_class = skip_typerefs(selection_class);
    if (selection_class != naming_class) gen_class_qualifier(naming_class);
    gen_unqualified_name(&rout->source_corresp, iek_routine);
  }  /* if */
}  /* gen_bound_function */


static void gen_expr(an_expr_node_ptr expr,
                     a_boolean        need_parens)
/*
Generate code for the indicated expression.  Put parentheses around it if
there's some possibility of precedence confusion and need_parens is TRUE.
*/
{
  /* Note: don't extract things from expr here in the declarations, because
     expr may be changed just below for the reference indirection case. */
  char             *opstr;
  an_expr_node_ptr operand_1, operand_2, args;
  a_boolean        operand_1_is_lvalue = FALSE;
  a_routine_ptr    rout;
  a_boolean        need_reference_close_paren = FALSE;

  check_assertion_str(expr != NULL, "gen_expr: NULL expression");
  if (expr->implicit_reference_indirection) {
    /* This node is or contains an extra indirection generated because
       of a C++ reference type.  The indirection has to be removed in the
       generated source code (because it will be put back in implicitly
       by the language rules). */
    if (is_operation_node(expr) &&
        expr->variant.operation.kind == (an_expr_operator_kind)eok_indirect) {
      /* This operation is an indirection, so we can eliminate the indirection
         and come out even. */
      expr = expr->variant.operation.operands;
    } else {
      /* Otherwise, just put a "&" in front of the node, which cancels the
         implicit indirection. */
      write_tok_ch('(');
      gen_ampersand(type_pointed_to(expr->type));
      need_reference_close_paren = TRUE;
      need_parens = TRUE;
    }  /* if */
  }  /* if */
  switch (expr->kind) {
    case enk_operation:
      /* Expression operation. */
      if (need_parens) m_write_tok_ch('(');
      operand_1 = expr->variant.operation.operands;
      operand_2 = operand_1->next;
      switch (expr->variant.operation.kind) {
        /* One-operand operators. */
        case eok_indirect:
          if (operand_1->implicit_reference_indirection) {
            /* An indirection over a node with an implicit reference
               indirection.  The two can be cancelled out. */
            operand_1->implicit_reference_indirection = FALSE;
            gen_expression(operand_1);
            operand_1->implicit_reference_indirection = TRUE;
            goto done_with_operation;
          } else if (operand_1->kind == (an_expr_node_kind)enk_operation &&
                     operand_1->variant.operation.kind ==
                                            (an_expr_operator_kind)eok_field) {
            an_expr_node_ptr sel_operand_1 =
                                         operand_1->variant.operation.operands;
            /* Optimize "*" on top of an eok_field. */
            gen_simple_field_selection(sel_operand_1, sel_operand_1->next);
            goto done_with_operation;
          }  /* if */
          opstr = "*";
          break;
        case eok_inegate:
        case eok_fnegate:
          opstr = "-";
          break;
        case eok_not:
          write_tok_ch('!');
          gen_boolean_controlling_expression(operand_1);
          goto done_with_operation;
        case eok_cast:
          /* Normal casts can be eliminated if they are implicit. */
          /* But watch out for casts that implement the implicit type decay
             from array to pointer, or function to pointer. */
          /* This is necessary in cases where a function is called with
             an argument of a type that can be implicitly converted to
             a parameter type that uses a prototype scope type.  There's
             no way to write the cast explicitly, because the type can't
             be named at the call site. */
          if (expr->variant.operation.compiler_generated &&
              !is_pointer_type(expr->type)) {
            gen_expression(operand_1);
          } else {
            gen_cast(expr->type);
            gen_expr_with_parens(operand_1);
          }  /* if */
          goto done_with_operation;
        case eok_base_class_cast:
        case eok_derived_class_cast:
        case eok_pm_base_class_cast:
        case eok_pm_derived_class_cast:
          /* Special casts. */
          gen_cast(expr->type);
          gen_expr_with_parens(operand_1);
          goto done_with_operation;
        case eok_lvalue_cast:
          unexpected_condition_str("gen_expr: eok_lvalue_cast as rvalue");
        case eok_complement:
          opstr = "~";
          break;
        case eok_fpost_incr:
        case eok_ipost_incr:
        case eok_ppost_incr:
          /* Post-increment operators. */
          gen_lvalue(operand_1);
          write_tok_str("++");
          goto done_with_operation;
        case eok_ipre_incr:
        case eok_fpre_incr:
        case eok_ppre_incr:
          /* Pre-increment operators. */
          opstr = "++";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_fpost_decr:
        case eok_ipost_decr:
        case eok_ppost_decr:
          /* Post-decrement operators. */
          gen_lvalue(operand_1);
          write_tok_str("--");
          goto done_with_operation;
        case eok_ipre_decr:
        case eok_fpre_decr:
        case eok_ppre_decr:
          /* Pre-decrement operators. */
          opstr = "--";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_iadd:
        case eok_fadd:
        case eok_padd:
        case eok_padd_subsc:
          opstr = "+";
          break;
        case eok_isubtract:
        case eok_fsubtract:
        case eok_psubtract:
        case eok_pdiff:
          opstr = "-";
          break;
        case eok_imultiply:
        case eok_fmultiply:
          opstr = "*";
          break;
        case eok_idivide:
        case eok_fdivide:
          opstr = "/";
          break;
        case eok_ieq:
        case eok_feq:
        case eok_peq:
        case eok_pmeq:
          opstr = "==";
          break;
        case eok_ine:
        case eok_fne:
        case eok_pne:
        case eok_pmne:
          opstr = "!=";
          break;
        case eok_igt:
        case eok_fgt:
        case eok_pgt:
          opstr = ">";
          break;
        case eok_ilt:
        case eok_flt:
        case eok_plt:
          opstr = "<";
          break;
        case eok_ige:
        case eok_fge:
        case eok_pge:
          opstr = ">=";
          break;
        case eok_ile:
        case eok_fle:
        case eok_ple:
          opstr = "<=";
          break;
        case eok_remainder:
          opstr = "%";
          break;
        case eok_iassign:
        case eok_fassign:
        case eok_passign:
        case eok_sassign:
        case eok_pmassign:
          opstr = "=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_imultiply_assign:
        case eok_fmultiply_assign:
          opstr = "*=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_idivide_assign:
        case eok_fdivide_assign:
          opstr = "/=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_remainder_assign:
          opstr = "%=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_iadd_assign:
        case eok_fadd_assign:
        case eok_padd_assign:
          opstr = "+=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_isubtract_assign:
        case eok_fsubtract_assign:
        case eok_psubtract_assign:
          opstr = "-=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_shiftl_assign:
          opstr = "<<=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_shiftr_assign:
          opstr = ">>=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_and_assign:
          opstr = "&=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_or_assign:
          opstr = "|=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_xor_assign:
          opstr = "^=";
          operand_1_is_lvalue = TRUE;
          break;
        case eok_bassign:
          /* eok_bassign is generated only by IL lowering */
          unexpected_condition_str("gen_expr: eok_bassign");
          break;
        case eok_subscript:
          gen_expr_with_parens(operand_1);
          write_tok_ch('[');
          gen_expression(operand_2);
          write_tok_ch(']');
          goto done_with_operation;
        case eok_field:
          gen_ampersand(type_pointed_to(expr->type));
          write_tok_ch('(');
          gen_simple_field_selection(operand_1, operand_2);
          write_tok_ch(')');
          goto done_with_operation;
        case eok_value_field:
        case eok_value_bit_field:
          /* Selection of a field or bit field from an rvalue.  Not used
             in C++ except for simple aggregate classes. */
          gen_expr_with_parens(operand_1);
          write_tok_ch('.');
          gen_field_reference(operand_2);
          goto done_with_operation;
        case eok_bit_field:
          /* This operator shouldn't get past gen_lvalue. */
          unexpected_condition_str("gen_expr: eok_bit_field as rvalue");
        case eok_extract_bit_field:
          gen_simple_field_selection(operand_1, operand_2);
          goto done_with_operation;
        case eok_pm_field:
          /* C++ "->*" operator. */
          gen_ampersand(type_pointed_to(expr->type));
          write_tok_ch('(');
          gen_lvalue(operand_1);
          write_tok_str(".*");
          gen_expr_with_parens(operand_2);
          write_tok_ch(')');
          goto done_with_operation;
        case eok_shiftl:
          opstr = "<<";
          break;
        case eok_shiftr:
          opstr = ">>";
          break;
        case eok_and:
          opstr = "&";
          break;
        case eok_or:
          opstr = "|";
          break;
        case eok_xor:
          opstr = "^";
          break;
        case eok_comma:
          gen_expr_with_parens(operand_1);
          write_tok_str(", ");
          if (expr->variant.operation.returns_lvalue_instead_of_usual_rvalue) {
            gen_lvalue(operand_2);
          } else {
            gen_expr_with_parens(operand_2);
          }  /* if */
          goto done_with_operation;
        case eok_land:
          gen_boolean_controlling_expression(operand_1);
          write_tok_str(" && ");
          gen_boolean_controlling_expression(operand_2);
          goto done_with_operation;
        case eok_lor:
          gen_boolean_controlling_expression(operand_1);
          write_tok_str(" || ");
          gen_boolean_controlling_expression(operand_2);
          goto done_with_operation;
        case eok_question:
          /* Three operand operator. */
          gen_boolean_controlling_expression(operand_1);
          write_tok_str(" ? ");
          if (expr->variant.operation.returns_lvalue_instead_of_usual_rvalue) {
            gen_lvalue(operand_2);
          } else {
            gen_expr_with_parens(operand_2);
          }  /* if */
          write_tok_str(" : ");
          if (expr->variant.operation.returns_lvalue_instead_of_usual_rvalue) {
            gen_lvalue(operand_2->next);
          } else {
            gen_expr_with_parens(operand_2->next);
          }  /* if */
          goto done_with_operation;
        case eok_call:
          /* Call (nonvirtual). */
          args = operand_2;
          /* Put out the function to call. */
          if (operand_1->kind == (an_expr_node_kind)enk_routine_address) {
            /* We can tell which routine is being called. */
            a_type_ptr rout_type;
            rout = operand_1->variant.routine;
            rout_type = skip_typerefs(rout->type);
            if (rout_type->variant.routine.extra_info->
                                            implicit_this_param_type != NULL) {
              /* Nonstatic member function call, so put out the selector object
                 first. */
              gen_bound_function(args, operand_1, /*suppress_virtual=*/TRUE);
              args = args->next;
            } else {
              /* Nonmember function or static member function. */
              gen_routine_name(rout);
            }  /* if */
          } else {
            /* Specific routine is not known (e.g., call through a pointer). */
            /* Note that this can't be a member function. */
            gen_lvalue(operand_1);
          }  /* if */
          /* Put out the arguments. */
          gen_argument_list(args, type_pointed_to(operand_1->type),
                            /*skip_num=*/0);
          goto done_with_operation;
        case eok_virtual_call:
          /* Call (virtual). */
          gen_bound_function(operand_2, operand_1, /*suppress_virtual=*/FALSE);
          gen_argument_list(operand_2->next, type_pointed_to(operand_1->type),
                            /*skip_num=*/0);
          goto done_with_operation;
        case eok_pm_call:
          /* Call of a function identified by a "->*" operation.  First
             operand is the pointer-to-member; the second is the object. */
          write_tok_ch('(');
          gen_expr_with_parens(operand_2);
          write_tok_str(" ->* ");
          gen_expr_with_parens(operand_1);
          write_tok_ch(')');
          /* Get the routine type from the pointer-to-member type of the
             first operand. */
          { a_type_ptr type = operand_1->type;
            type = skip_typerefs(type);
            check_assertion(type->kind == (a_type_kind)tk_ptr_to_member);
            type = type->variant.ptr_to_member.type;
            /* Generate the argument list. */
            gen_argument_list(operand_2->next, type, /*skip_num=*/0);
          }
          goto done_with_operation;
        case eok_virtual_function_ptr:
          /* Used for anachronism of casting a bound function pointer to
             a normal function pointer.  First operand is the address of
             a virtual function, the second is a pointer to a class object. */
          gen_bound_function(operand_2, operand_1, /*suppress_virtual=*/FALSE);
          goto done_with_operation;
        case eok_vacuous_destructor_call:
          /* Explicit call of a destructor for a type that doesn't have one,
             e.g., "p->int::~int()". */
          gen_expr_with_parens(operand_1);
          write_tok_str("->");
          /* Use the type name to create a "destructor" name. */
          { a_type_ptr type = type_pointed_to(operand_1->type);
            gen_type(type);
            write_str("::~");
            if (is_class_type_kind(type->kind)) {
              /* Class case. */
              /* Don't use gen_type here, because we don't want the template
                 arguments, if any, listed.  Also, we want to output a
                 partial token. */
              write_str(type->source_corresp.name);
            } else {
              /* Case like "int::~int". */
              gen_type(type);
            }  /* if */
          }
          write_tok_str("()");
          goto done_with_operation;
        default:
          unexpected_condition_str("gen_expr: bad expression operator");
      }  /* switch */
      /* General-case processing: */
      if (operand_2 == NULL) {
        /* Unary operator; operator goes first. */
        write_tok_str(opstr);
      }  /* if */
      /* Generate the first operand. */
      if (operand_1_is_lvalue) {
        gen_lvalue(operand_1);
      } else {
        gen_expr_with_parens(operand_1);
      }  /* if */
      if (operand_2 != NULL) {
        /* Binary operator. */
        m_write_space();
        write_tok_str(opstr);
        m_write_space();
        gen_expr_with_parens(operand_2);
      }  /* if */
done_with_operation:
      if (need_parens) m_write_tok_ch(')');
      break;
    case enk_constant:
      gen_constant(expr->variant.constant, need_parens);
      break;
    case enk_variable_address:
      if (need_parens) m_write_tok_ch('(');
      gen_ampersand(expr->variant.variable->type);
      gen_variable_name(expr->variant.variable);
      if (need_parens) m_write_tok_ch(')');
      break;
    case enk_variable:
      gen_variable_name(expr->variant.variable);
      break;
    case enk_routine_address:
      if (need_parens) write_tok_ch('(');
      gen_ampersand(expr->variant.routine->type);
      gen_routine_name(expr->variant.routine);
      if (need_parens) write_tok_ch(')');
      break;
    case enk_throw:
      /* Throw. */
      if (need_parens) write_tok_ch('(');
      write_tok_str("throw");
      /* A NULL pointer means a rethrow, e.g., "throw;". */
      if (expr->variant.throw_info != NULL) {
        a_throw_supplement_ptr tsp = expr->variant.throw_info;
        write_space();
        gen_dynamic_init(tsp->dynamic_init, tsp->type,
                         /*parenthesized_init=*/FALSE,
                         /*force_parens=*/FALSE);
      }  /* if */
      if (need_parens) write_tok_ch(')');
      break;
    case enk_object_lifetime:
      /* Definition of object lifetime (for temporaries).  Ignored. */
      gen_expr(expr->variant.object_lifetime.expr, need_parens);
      break;
    case enk_temp_init:
      /* Temporary creation/initialization. */
      /* The temporary is being used as an rvalue here, so the result of
         the node should be the value of the temporary. */
      check_assertion_str(!expr->variant.init.result_is_addr,
                          "gen_expr: enk_temp_init returning addr as rvalue");
      gen_temp_init(expr);
      break;
    case enk_new_delete:
      /* new or delete operation. */
      gen_new_delete(expr);
      break;
    case enk_field:
      /* enk_field entries are supposed to be handled before this. */
      unexpected_condition_str("gen_expr: enk_field");
    default:
      unexpected_condition_str("gen_expr: bad expr node kind");
  }  /* switch */
  /* If an extra set of parentheses was added because of the reference
     indirection trick above. close the set now. */
  if (need_reference_close_paren) write_tok_ch(')');
}  /* gen_expr */


static void gen_full_expression(an_expr_node_ptr expr)
/*
Generate code for the indicated expression, which is a full expression
(it's not part of another expression).
*/
{
  /* For C, process any tags declared within the expression (e.g., in
     casts). */
  skip_embedded_declarations();
  gen_expression(expr);
}  /* gen_full_expression */


